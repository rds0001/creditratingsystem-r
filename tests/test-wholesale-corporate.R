library(creditratingsystem)
example_path <- system.file("examples/wholesale_corporate.R", package="creditratingsystem")
stopifnot(nzchar(example_path))
source(example_path)
result <- run_wholesale_corporate()
stopifnot(setequal(names(result$variants),c("SME","large_corporate","senior","subordinated","secured")))
stopifnot(max(abs(unlist(result$calibrated)-0.17912878474779))<1e-7)
stopifnot(identical(unname(vapply(result$variants[c("senior","subordinated","secured")],function(x)x$economic_loss_at_default,numeric(1))),c(0,20,10)))
stopifnot(all(vapply(result$variants[c("senior","subordinated","secured")],function(x)x$negative_status,character(1))=="NO_ROUTE"))
