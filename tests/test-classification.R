library(creditratingsystem)
err <- function(expr, code) {
  caught <- tryCatch(force(expr), creditratingsystem_error = identity)
  stopifnot(inherits(caught, "creditratingsystem_error"), identical(caught$code, code))
}
near <- function(x, y, tol = 1e-7) stopifnot(isTRUE(all.equal(unname(x), unname(y), tolerance = tol, check.attributes = FALSE)))
target <- list(event = "default", horizon = 1, time_unit = "years", probability_measure = "PHYSICAL", conditioning = "performing_at_observation")
training <- list(data_fingerprint = "independent-two-group-counts", split_id = "train", known_at = "2025-12-31", data_origin = "SYNTHETIC")
x <- matrix(c(0, 0, 1, 1), ncol = 1)
y <- c(0, 1, 0, 1)
fit <- function(link, X = x, Y = y, ...) {
  options <- utils::modifyList(list(X_train = X, y_train = Y, link = link, feature_order = "group",
    fit_intercept = TRUE, target = target, training = training, model_id = "binary-example",
    model_version = "1", weights = c(8, 2, 4, 6)), list(...), keep.null = TRUE)
  do.call(fit_binary_glm, options)
}
for (link in c("logit", "probit", "cloglog")) {
  rate <- c(.2, .6)
  eta <- switch(link, logit = qlogis(rate), probit = qnorm(rate), cloglog = log(-log1p(-rate)))
  result <- fit(link)
  near(unlist(result$model$parameters$coefficients), c(eta[1], eta[2]-eta[1]))
  near(predict_pd(result, matrix(c(0, 1), ncol = 1), "group", target)$value, rate)
  near(result$diagnostics$log_likelihood, 2*log(.2)+8*log(.8)+6*log(.6)+4*log(.4))
  derivative <- switch(link, logit = rate*(1-rate), probit = dnorm(eta), cloglog = (1-rate)*(-log1p(-rate)))
  v <- rate*(1-rate)/(10*derivative^2)
  covariance <- matrix(c(v[1], -v[1], -v[1], sum(v)), 2)
  near(matrix(unlist(result$model$parameters$covariance), 2, byrow = TRUE), covariance)
  stopifnot(result$provenance$data_origin == "SYNTHETIC")
  intercept <- fit(link, X = matrix(numeric(), 2, 0), Y = c(0, 1), feature_order = character(), weights = c(7, 3))
  near(predict_pd(intercept, matrix(numeric(), 1, 0), character(), target)$value, .3)
  shifted <- fit(link, offset = rep(.3, 4))
  near(unlist(shifted$model$parameters$coefficients), unlist(result$model$parameters$coefficients)-c(.3, 0))
  near(predict_pd(shifted, matrix(c(0, 1), ncol = 1), "group", target, offset = c(.3, .3))$value, rate)
  doubled <- fit(link, weights = c(16, 4, 8, 12))
  near(unlist(doubled$model$parameters$covariance), unlist(result$model$parameters$covariance)/2)
}
err(fit("logit", matrix(c(-2,-1,1,2), ncol = 1), c(0,0,1,1), weights = NULL), "SEPARATION")
err(fit("logit", matrix(c(-1,0,0,1), ncol = 1), c(0,0,1,1), weights = NULL), "SEPARATION")
err(fit("logit", matrix(rep(1,4), ncol = 1)), "RANK_DEFICIENT")
err(fit("logit", max_iter = 1L), "NON_CONVERGENCE")
err(fit("logit", weights = c(1,.2,1,1)), "INVALID_WEIGHTS")
err(fit("logit", weight_type = "sampling"), "INVALID_WEIGHT_TYPE")
